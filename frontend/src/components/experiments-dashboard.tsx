"use client";

import { useCallback, useEffect, useState } from "react";
import { Activity, ArrowUpRight, Check, CircleHelp, Clock3, FlaskConical, LoaderCircle, RadioTower, Route, Scale } from "lucide-react";
import { compareExperiments, getScenarios } from "@/lib/api";
import type { ExperimentComparison, Metrics, RoutingPolicy, ScenarioSummary } from "@/lib/contracts";

const SECOND = 1_000_000;
const defaultHorizonSeconds = 3600;

const metricDefinitions = [
  {
    key: "delivery_ratio",
    title: "Delivery ratio",
    direction: "higher",
    formula: "delivered by H ÷ generated by H",
    meaning: "Share of generated bundles delivered by the observation cutoff. Pending bundles count as undelivered, not expired.",
    format: (value: number | null) => value == null ? "—" : `${(value * 100).toFixed(1)}%`,
  },
  {
    key: "median_delivery_latency_us",
    title: "Median delivery latency",
    direction: "lower",
    formula: "median(delivery time − creation time), delivered bundles only",
    meaning: "Typical time to deliver among successful bundles. Undelivered bundles have no invented latency.",
    format: (value: number | null) => value == null ? "—" : `${(value / SECOND).toFixed(2)} s`,
  },
  {
    key: "mean_hop_count",
    title: "Mean hops to delivery",
    direction: "lower",
    formula: "successful receiver admissions ÷ delivered bundles",
    meaning: "Average number of successful forwarding hops among delivered bundles; retries do not count as hops.",
    format: (value: number | null) => value == null ? "—" : value.toFixed(2),
  },
  {
    key: "expiration_ratio",
    title: "Expiration ratio",
    direction: "lower",
    formula: "expired by H ÷ generated by H",
    meaning: "Fraction that reached TTL expiry. This can be lower than the undelivered share because pending bundles are right-censored at H.",
    format: (value: number | null) => value == null ? "—" : `${(value * 100).toFixed(1)}%`,
  },
] as const;

const contextMetrics = [
  {
    key: "contact_utilization_fraction",
    title: "Contact utilization",
    formula: "serialized payload bits ÷ scheduled contact capacity bits clipped to [0, H]",
    format: (value: number | null) => value == null ? "—" : `${(value * 100).toFixed(1)}%`,
    note: "Context only: high use can mean efficient use or a saturated network.",
  },
  {
    key: "mean_total_buffer_occupancy_bytes",
    title: "Mean buffered data",
    formula: "(1 ÷ H) ∫₀ᴴ total occupied bytes(t) dt",
    format: (value: number | null) => value == null ? "—" : `${(value / 1_000_000).toFixed(1)} MB`,
    note: "Context only: interpret with delivered and pending counts.",
  },
] as const;

type MetricKey = typeof metricDefinitions[number]["key"];
type Direction = "higher" | "lower";

function metricValue(metrics: Metrics, key: MetricKey): number | null {
  return metrics[key];
}

function formatPolicy(policy: RoutingPolicy) {
  return policy === "contact_aware_earliest_arrival" ? "Contact-aware earliest arrival" : "Static minimum hop";
}

function compareMetric(left: number | null, right: number | null, direction: Direction): "left" | "right" | "tie" | "na" {
  if (left == null || right == null) return "na";
  if (Math.abs(left - right) < 1e-12) return "tie";
  return (direction === "higher" ? left > right : left < right) ? "left" : "right";
}

function primaryWinner(left: Metrics, right: Metrics): { policy: "left" | "right" | null; reason: string } {
  const delivery = compareMetric(left.delivery_ratio, right.delivery_ratio, "higher");
  if (delivery === "left" || delivery === "right") return { policy: delivery, reason: "higher delivery ratio" };

  const latency = compareMetric(left.median_delivery_latency_us, right.median_delivery_latency_us, "lower");
  if (latency === "left" || latency === "right") return { policy: latency, reason: "lower median latency at the same delivery ratio" };

  const hops = compareMetric(left.mean_hop_count, right.mean_hop_count, "lower");
  if (hops === "left" || hops === "right") return { policy: hops, reason: "fewer mean forwarding hops after delivery ratio and latency tie" };
  return { policy: null, reason: "the primary outcome metrics are tied or unavailable" };
}

export function ExperimentsDashboard() {
  const [scenarios, setScenarios] = useState<ScenarioSummary[]>([]);
  const [selectedScenarioIds, setSelectedScenarioIds] = useState<string[]>([]);
  const [comparison, setComparison] = useState<ExperimentComparison | null>(null);
  const [seed, setSeed] = useState(42);
  const [horizonSeconds, setHorizonSeconds] = useState(defaultHorizonSeconds);
  const [loadingScenarios, setLoadingScenarios] = useState(true);
  const [running, setRunning] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const runComparison = useCallback(async (scenarioIds: string[], runSeed: number, runHorizon: number) => {
    if (scenarioIds.length === 0) {
      setError("Select at least one network setting to compare.");
      return;
    }
    setRunning(true);
    setError(null);
    try {
      setComparison(await compareExperiments(scenarioIds, runSeed, runHorizon * SECOND));
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "The backend comparison failed.");
      setComparison(null);
    } finally {
      setRunning(false);
    }
  }, []);

  useEffect(() => {
    let cancelled = false;
    const load = async () => {
      try {
        const available = await getScenarios();
        if (cancelled) return;
        const presetIds = available.map((scenario) => scenario.scenario_id);
        setScenarios(available);
        setSelectedScenarioIds(presetIds);
        setLoadingScenarios(false);
        await runComparison(presetIds, 42, defaultHorizonSeconds);
      } catch (cause) {
        if (!cancelled) {
          setError(cause instanceof Error ? cause.message : "Could not load the scenario catalog.");
          setLoadingScenarios(false);
        }
      }
    };
    void load();
    return () => { cancelled = true; };
  }, [runComparison]);

  const toggleScenario = (scenarioId: string) => {
    setSelectedScenarioIds((current) => current.includes(scenarioId)
      ? current.filter((item) => item !== scenarioId)
      : [...current, scenarioId]);
  };

  return (
    <main className="experiment-page">
      <header className="experiment-hero">
        <div>
          <span className="eyebrow">BACKEND-RUN ROUTING STUDY</span>
          <h1>Which routing strategy performs better?</h1>
          <p>Run both algorithms against the same network, traffic, seed, and observation window. Compare delivery outcomes across the project’s LEO presets.</p>
        </div>
        <div className="experiment-pair-badge"><Scale size={18} /><span>Matched runs<br /><b>only routing changes</b></span></div>
      </header>

      <div className="experiment-workspace">
        <aside className="experiment-controls panel">
          <div className="panel-heading"><div className="heading-icon blue"><FlaskConical size={16} /></div><h2>Comparison setup</h2></div>
          <label className="field-label" htmlFor="experiment-seed">Random seed</label>
          <input id="experiment-seed" className="experiment-input" type="number" value={seed} onChange={(event) => setSeed(Number(event.target.value))} />
          <label className="field-label" htmlFor="experiment-horizon">Observation window (seconds)</label>
          <input id="experiment-horizon" className="experiment-input" type="number" min={60} max={3600} step={60} value={horizonSeconds} onChange={(event) => setHorizonSeconds(Math.max(60, Math.min(3600, Number(event.target.value) || 60)))} />
          <div className="experiment-setting-heading"><span>Network settings</span><small>{selectedScenarioIds.length} selected</small></div>
          <div className="experiment-scenario-options">
            {loadingScenarios ? <div className="experiment-loading"><LoaderCircle className="spin" size={15} /> Loading presets…</div> : scenarios.map((scenario) => (
              <label className={`experiment-scenario-option ${selectedScenarioIds.includes(scenario.scenario_id) ? "selected" : ""}`} key={scenario.scenario_id}>
                <input type="checkbox" checked={selectedScenarioIds.includes(scenario.scenario_id)} onChange={() => toggleScenario(scenario.scenario_id)} />
                <span><b>{scenario.name}</b><small>{scenario.focus}</small></span>
              </label>
            ))}
          </div>
          <button className="primary full-width experiment-run-button" onClick={() => void runComparison(selectedScenarioIds, seed, horizonSeconds)} disabled={running || loadingScenarios || selectedScenarioIds.length === 0}>
            {running ? <LoaderCircle className="spin" size={16} /> : <Activity size={16} />}
            {running ? "Running backend simulations…" : "Run comparison"}
          </button>
          <p className="experiment-run-note">Each selected setting runs both routing policies in the backend. Orbital contacts are planned through the configured bundle TTL; metrics are measured at the selected cutoff.</p>
        </aside>

        <section className="experiment-results-column">
          {error && <div className="scenario-error"><CircleHelp size={16} />{error}</div>}
          {running && <div className="experiment-progress panel"><LoaderCircle className="spin" size={19} /><div><b>Running matched scenarios</b><span>Each network setting is simulated twice with identical inputs.</span></div></div>}
          {!running && comparison && <>
            <div className="experiment-result-summary">
              <div><span className="eyebrow">BACKEND RESULTS</span><h2>{comparison.scenarios.length} settings · {comparison.scenarios.length * 2} simulation runs</h2></div>
              <span className="experiment-run-meta">Seed {comparison.random_seed} <i /> {(comparison.horizon_us / SECOND).toFixed(0)} s cutoff</span>
            </div>
            <div className="experiment-result-list">
              {comparison.scenarios.map((item) => {
                const left = item.results.find((result) => result.routing_policy === "contact_aware_earliest_arrival");
                const right = item.results.find((result) => result.routing_policy === "static_minimum_hop");
                if (!left || !right) return null;
                const winner = primaryWinner(left.metrics, right.metrics);
                const winnerResult = winner.policy === "left" ? left : winner.policy === "right" ? right : null;
                const deliveredDelta = left.metrics.delivered_count - right.metrics.delivered_count;
                return (
                  <article className="scenario-comparison-card panel" key={item.scenario.scenario_id}>
                    <div className="scenario-comparison-header">
                      <div><span className="eyebrow">{item.scenario.satellite_count} SATELLITES · {item.scenario.orbital_contact_generation ? "GEOMETRY CONTACTS" : "SCHEDULED CONTACTS"}</span><h3>{item.scenario.name}</h3><p>{item.scenario.description}</p></div>
                      <div className={`comparison-winner ${winnerResult ? "has-winner" : ""}`}><Check size={14} /><span>{winnerResult ? `${formatPolicy(winnerResult.routing_policy)} leads` : "No clear leader"}</span></div>
                    </div>
                    <div className="scenario-setting-chips">
                      {item.scenario.configuration.bundles.slice(0, 1).map((bundle) => <span key={bundle.bundle_id}><Route size={12} /> {bundle.payload_bytes / 1_000_000} MB bundles</span>)}
                      {item.scenario.configuration.bundle_generation_interval_us != null && <span><Clock3 size={12} /> Every {(item.scenario.configuration.bundle_generation_interval_us / SECOND).toFixed(0)} s</span>}
                      <span><RadioTower size={12} /> {item.scenario.satellite_count} relay satellites</span>
                    </div>

                    <div className="policy-headings"><span>Metric</span><b>{formatPolicy(left.routing_policy)}</b><b>{formatPolicy(right.routing_policy)}</b><span>Advantage</span></div>
                    <div className="comparison-metric-list">
                      {metricDefinitions.map((metric) => {
                        const leftValue = metricValue(left.metrics, metric.key);
                        const rightValue = metricValue(right.metrics, metric.key);
                        const advantage = compareMetric(leftValue, rightValue, metric.direction);
                        return <div className="comparison-metric-row" key={metric.key}>
                          <span className="comparison-metric-name">{metric.title}<small>{metric.direction === "higher" ? "Higher is better" : "Lower is better"}</small></span>
                          <b className={advantage === "left" ? "metric-leading" : ""}>{metric.format(leftValue)}</b>
                          <b className={advantage === "right" ? "metric-leading" : ""}>{metric.format(rightValue)}</b>
                          <span className={`metric-advantage ${advantage === "tie" || advantage === "na" ? "neutral" : ""}`}>{advantage === "left" ? "Contact-aware" : advantage === "right" ? "Static min-hop" : advantage === "na" ? "Unavailable" : "Tie"}</span>
                        </div>;
                      })}
                      {contextMetrics.map((metric) => <div className="comparison-metric-row contextual" key={metric.key}>
                        <span className="comparison-metric-name">{metric.title}<small>Context, not ranked</small></span>
                        <b>{metric.format(left.metrics[metric.key])}</b><b>{metric.format(right.metrics[metric.key])}</b><span className="metric-advantage neutral">Context</span>
                      </div>)}
                    </div>

                    <div className="comparison-inference">
                      <div className="inference-icon"><CircleHelp size={15} /></div>
                      <div><b>What this comparison suggests</b><p>{winnerResult
                        ? `${formatPolicy(winnerResult.routing_policy)} ranks ahead by ${winner.reason}. At this cutoff it delivered ${Math.abs(deliveredDelta)} ${Math.abs(deliveredDelta) === 1 ? "more bundle" : "more bundles"} than ${formatPolicy(winnerResult.routing_policy === left.routing_policy ? right.routing_policy : left.routing_policy)}.`
                        : "The primary outcome metrics are tied at this cutoff. This run shows no measurable routing advantage under these settings; it does not prove the strategies are equivalent in other scenarios."}
                        {` The ranking prioritizes delivery ratio, then median delivered latency, then mean hops.`}</p>
                        <small>Generated: {left.metrics.generated_count} · delivered: {left.metrics.delivered_count} / {right.metrics.delivered_count} · pending or otherwise undelivered at cutoff: {left.metrics.undelivered_count} / {right.metrics.undelivered_count} · expired: {left.metrics.expired_count} / {right.metrics.expired_count}</small>
                      </div>
                    </div>
                  </article>
                );
              })}
            </div>
          </>}
          {!running && !comparison && !error && <div className="experiment-empty panel"><FlaskConical size={24} /><b>Choose settings and run the comparison</b><span>Results will come from paired backend simulations.</span></div>}
        </section>
      </div>

      <section className="metric-methodology panel">
        <div className="panel-heading"><div className="heading-icon cyan"><CircleHelp size={16} /></div><h2>Metric formulas and interpretation</h2><span className="section-tag">METHOD</span></div>
        <div className="metric-method-grid">
          {metricDefinitions.map((metric) => <article className="metric-method-card" key={metric.key}><span>{metric.title}</span><code>{metric.formula}</code><p>{metric.meaning}</p></article>)}
          {contextMetrics.map((metric) => <article className="metric-method-card contextual" key={metric.key}><span>{metric.title} · contextual</span><code>{metric.formula}</code><p>{metric.note}</p></article>)}
        </div>
        <p className="methodology-note"><ArrowUpRight size={13} /> Overall ranking is lexicographic: delivery ratio first, median latency second, mean hops third. Buffer occupancy and contact utilization are reported as context because neither has a universally better direction.</p>
      </section>
    </main>
  );
}
